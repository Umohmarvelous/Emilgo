// The props' table (v4 rework R9; the owner: "use all assets you showed me in
// the plan document because i am not seeing them"): every CC0 model the
// pipeline built for `use: "prop"`, its size and where it goes, written into
// src/maps/open/propTable.ts. The layout (client and server alike) places them
// from this table, so the solids agree without anyone loading a model.
// Append-only: a prop's index is its place in vital.json (a placement's variant
// carries it), so a new prop never moves an old one.
//
//   node tools/assets/props.mjs        (after pipeline.mjs build)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const vital = JSON.parse(readFileSync(join(here, "vital.json"), "utf8"));
const man = JSON.parse(readFileSync(join(here, "out/manifest.json"), "utf8")).models;
const rows = [];
for (const m of vital.models) {
  if (m.use !== "prop") continue;
  const b = man[m.id];
  const built = !!(b && b.size);
  const [w, h, d] = built ? b.size : [0.6, 0.6, 0.6];
  // Low things (under 0.45 m) you step over: no solid.
  const solid = !!m.solid && h >= 0.45;
  rows.push(`  { id: ${JSON.stringify(m.id)}, w: ${w}, h: ${h}, d: ${d}, solid: ${solid}, at: ${JSON.stringify(m.loc)}, built: ${built} },`);
}
const out = `// Generated by tools/assets/props.mjs from the asset pipeline's manifest. Do not edit.
// The CC0 props from Poly Haven (v4 rework R9): size in metres (w across x, h up, d along z),
// whether they stop you, and the places they go ("city", or a Meridian Max place's id).
// \`built: false\`: listed but not built yet (never placed).

export interface PropDef {
  id: string;
  w: number;
  h: number;
  d: number;
  solid: boolean;
  at: readonly string[];
  built: boolean;
}

export const PROPS: readonly PropDef[] = [
${rows.join("\n")}
];
`;
writeFileSync(join(here, "../../src/maps/open/propTable.ts"), out);
console.log(`${rows.length} props, ${rows.filter((r) => r.includes("built: true")).length} built`);
