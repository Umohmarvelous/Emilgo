// Copies the single-file EMILGO build into the app as a TypeScript string, so
// the Game tab can load it into a WebView with no network at all.
//
//   npm run build:emilgo     (from games/emilgo-games)  →  src/games/emilgo-games/redlightHtml.generated.ts

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../dist-emilgo/index.html");
const out = resolve(here, "../../../src/games/emilgo-games/redlightHtml.generated.ts");

const html = readFileSync(src, "utf8");
if (/<script[^>]+src=/.test(html)) throw new Error("embed: the EMILGO build still references an external script");
if (html.includes("vatar-games-v1.js")) throw new Error("embed: the EMILGO build must not include the Vatar SDK");

const hash = createHash("sha256").update(html).digest("hex").slice(0, 12);
const body = `// GENERATED by games/emilgo-games/scripts/embed.mjs — do not edit.
// EMILGO Games · Red Light, Green Light, single-file build for the EMILGO app.
// Rebuild with: npm run game:embed
/* eslint-disable */
export const REDLIGHT_BUILD = ${JSON.stringify(hash)};
export const REDLIGHT_HTML: string = ${JSON.stringify(html)};
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, body);
console.log(`embed: ${(html.length / 1024).toFixed(0)} KB → ${out} (build ${hash})`);
