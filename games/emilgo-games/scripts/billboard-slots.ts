// Writes the big world's billboard slots as a Supabase migration, from the world
// itself, so a board on the map can always be sold:
//   npx tsx scripts/billboard-slots.ts
// Run it again whenever MAX_BOARDS changes. Older ids keep their rows.

import { writeFileSync } from "node:fs";

import { buildMaxWorld } from "../src/maps/open/max";

const w = buildMaxWorld();
const named = w.areas.filter((a) => a.id.startsWith("mx-"));
const near = (x: number, z: number): string => {
  const inside = named.find((a) => Math.hypot(a.x - x, a.z - z) <= a.r);
  if (inside) return inside.name;
  const best = [...named].sort((a, b) => Math.hypot(a.x - x, a.z - z) - a.r - (Math.hypot(b.x - x, b.z - z) - b.r))[0];
  return `near ${best.name}`;
};
const KIND: Record<string, string> = { road: "Road", landmark: "Landmark", plaza: "Plaza entrance", route: "Danfo route", zone: "Zone wall" };
const rows = (w.boards ?? []).filter((b) => b.id.startsWith("mx-"));
const line = (b: (typeof rows)[number]) => `  ('${b.id}', 'max-world', '${b.kind}', ${b.premium ? "TRUE " : "FALSE"}, '${`Meridian Max: ${KIND[b.kind] ?? b.kind}, ${near(b.x, b.z)}`.replace(/'/g, "''")}')`;
const sql = `-- Generated by games/emilgo-games/scripts/billboard-slots.ts. Do not edit.
-- The big world's billboards (Meridian Max), so they can be sold like the city's.
-- Needs migration_game_billboards.sql first. Safe to run again, before or after
-- migration_game_billboards_v6.sql (which already carries these boards, numbered:
-- running this one is optional once v6 is in). It only adds missing boards and
-- never rewrites v6's names and numbers.

DO $$
BEGIN
  IF to_regclass('public.game_billboard_slots') IS NULL THEN
    RAISE EXCEPTION 'game_billboard_slots is missing: run migration_game_billboards.sql first, then this file (or just migration_game_billboards_v6.sql, which includes these boards).';
  END IF;
END $$;

INSERT INTO public.game_billboard_slots (id, map, kind, premium, label) VALUES
${rows.map(line).join(",\n")}
ON CONFLICT (id) DO NOTHING;
`;
writeFileSync(new URL("../../../supabase/migrations/migration_game_billboards_max.sql", import.meta.url), sql);
console.log(`${rows.length} slots (${rows.filter((b) => b.premium).length} premium)`);
